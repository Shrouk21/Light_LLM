#!/usr/bin/env python3
"""Write RESULTS.md: every test case and how each model did on it. Stdlib only.

Reads bench/prompts/*.jsonl, the newest bench/results/<alias>-*.jsonl per alias,
scripts/catalog.sh and logs/serve-<alias>-70.out. Regenerates the whole file.
"""
import html, json, os, re, time
from summary import LANES, ROOT, HERE, latest_results, other_users, summary_table

OUT = os.path.join(ROOT, "RESULTS.md")
THINK_BUDGET = 8192
LANE_TITLES = {
    "chat": "Chat: general knowledge",
    "code": "Code",
    "reasoning": "Reasoning, thinking off",
    "reasoning_think": "Reasoning, thinking on (Qwen3.5 models only)",
    "vision": "Vision: synthetic images",
}


def catalog():
    rows = {}
    with open(os.path.join(ROOT, "scripts", "catalog.sh")) as f:
        for m in re.finditer(r'^\s*"(.*\|.*)"\s*$', f.read(), re.M):
            p = m.group(1).replace('\\"', '"').split("|")
            rows[p[0]] = {"repo": p[1], "gib": p[2], "kv": p[3], "ctx": f"{int(p[4]):,}", "lanes": p[5].replace(",", ", ")}
    return rows


def serve_log(alias):
    """Predicted vs logged KV pool, concurrency and engine init time from the serve log."""
    path = os.path.join(ROOT, "logs", f"serve-{alias}-70.out")
    if not os.path.exists(path):
        return None
    s = open(path, errors="replace").read()
    grab = lambda pat: (re.findall(pat, s) or [None])[-1]
    pred, logged = grab(r"predicted KV : ~(\d+)"), grab(r"GPU KV cache size: ([\d,]+) tokens")
    return {"pred": int(pred) if pred else None,
            "logged": int(logged.replace(",", "")) if logged else None,
            "conc": grab(r"Maximum concurrency for ([\d,]+) tokens per request: ([\d.]+)x"),
            "init": grab(r"init engine .* took ([\d.]+) s"),
            "vllm": grab(r"version (\d+\.\d+\.\d+)")}


def prompts():
    out = {}
    for lane in ("chat", "code", "reasoning", "vision"):
        with open(os.path.join(HERE, "prompts", lane + ".jsonl")) as f:
            for l in f:
                if l.strip():
                    r = json.loads(l); out[(lane, r["id"])] = r
    for (lane, i), r in list(out.items()):
        if lane == "reasoning":
            out[("reasoning_think", i)] = dict(r, lane="reasoning_think")
    return out


def cell(text):
    """Make text safe inside a markdown table cell."""
    return html.escape(text, quote=False).replace("|", "\\|")


def snippet(r, n=120):
    if "error" in r:
        return "error: " + cell(r["error"][:n])
    t = " ".join(r.get("text", "").split())
    t = cell(t[:n] + ("…" if len(t) > n else "")) or "*(empty)*"
    if r.get("think"):
        if not r.get("text", "").strip() and r.get("tokens", 0) >= THINK_BUDGET - 64:
            return f"*ran out of budget*: {r['tokens']} tokens, {r.get('reasoning_chars', 0):,} chars of reasoning, no answer"
        t += f" *({r.get('reasoning_chars', 0):,} chars of reasoning)*"
    return t


def main():
    results = latest_results()
    summaries = {a: next(r for r in rows if r.get("kind") == "summary") for a, rows in results.items()}
    quality = {a: {(r["lane"], r["id"]): r for r in rows if r.get("kind") == "quality"} for a, rows in results.items()}
    models = list(results)
    cat, cases = catalog(), prompts()
    logs = {a: serve_log(a) for a in models}
    vllm = next((l["vllm"] for l in logs.values() if l and l["vllm"]), "?")
    stamps = sorted(s["ts"] for s in summaries.values())
    contended = [a for a, s in summaries.items() if s.get("other_users_peak_mib")]
    ran = lambda lane, i: [a for a in models if (lane, i) in quality[a]]
    L = []
    w = L.append

    # --- header and setup ---------------------------------------------------
    w("# Model benchmark results\n")
    w(f"*Generated by `python3 bench/report.py` on {time.strftime('%Y-%m-%d %H:%M')}. "
      "Do not edit by hand; re-run the script instead.*\n")
    w("Nine local models were served one at a time with vLLM and asked the same 40 questions. "
      "This page shows the overall scores, then every question with every model's answer.\n")
    w("## Setup\n")
    w("| | |\n|---|---|")
    w("| GPU | Quadro RTX 8000, 48 GiB, compute capability 7.5 (Turing), shared lab machine |")
    w(f"| Engine | vLLM {vllm}, one model at a time, served as `local-model` |")
    w("| Resource cap | 70% of the GPU memory free at launch, 22 of 32 CPU cores, 70% of available RAM |")
    w(f"| Runs | {stamps[0][:16].replace('T', ' ')} to {stamps[-1][:16].replace('T', ' ')} |")
    w("")
    w("**Method.** Each question is sent once at temperature 0 with thinking mode off, and the answer "
      "is scored by a regular expression (the *Expected* line under each question). The Qwen3.5 models "
      f"answer the reasoning questions a second time with thinking on ({THINK_BUDGET}-token budget, "
      "temperature 0.6, top_p 0.95). A load test then runs 256-token generations at 1, 4 and 8 "
      "concurrent requests.\n")
    w("| Model | Repository | Weights | Max context | Lanes |\n|---|---|---|---|---|")
    for a in models:
        c = cat.get(a, {})
        w(f"| `{a}` | `{c.get('repo', '?')}` | {c.get('gib', '?')} GiB | {c.get('ctx', '?')} | {c.get('lanes', '?')} |")
    w("")

    # --- scoreboard ---------------------------------------------------------
    w("## Scoreboard\n")
    w(summary_table(summaries))
    w("\n*TTFT* is time to first token. *tok/s (1 req)* is the speed one user sees; *tok/s (8 conc.)* "
      "is total output with 8 requests at once. *Peak GPU* is the whole card, including other users.\n")
    if contended:
        w(f"⚠ **{', '.join(f'`{a}`' for a in contended)}**: measured while another user's job was on the "
          "GPU, so the speed figures are lower than the model's real speed. The scores are unaffected.\n")

    # --- key findings -------------------------------------------------------
    w("## Key findings\n")
    for lane in LANES:
        scored = {a: summaries[a]["quality"][lane]["pass"] for a in models if lane in summaries[a]["quality"]}
        if scored:
            top = max(scored.values()); n = summaries[next(iter(scored))]["quality"][lane]["n"]
            best = [f"`{a}`" for a, v in scored.items() if v == top]
            rest = [f"`{a}`" for a, v in scored.items() if v != top]
            who = ("every model" if not rest else f"all except {', '.join(rest)}") if len(best) > 2 and len(best) > len(rest) \
                else ", ".join(best)
            w(f"- **{LANE_TITLES[lane]}:** best score {top}/{n}, by {who}")
    clean = [a for a in models if a not in contended]
    for key, label, unit in (("1", "Fastest for one request", "mean_decode_tok_s"),
                             ("8", "Most output with 8 concurrent requests", "agg_tok_s")):
        a = max(clean, key=lambda m: summaries[m]["load"].get(key, {}).get(unit, 0))
        w(f"- **{label}:** `{a}` at {summaries[a]['load'][key][unit]} tok/s")
    for lane in [l for l in LANES if l != "reasoning_think"]:  # think failures are covered below
        for i in sorted({i for (l, i) in cases if l == lane}):
            who = ran(lane, i)
            if who and not any(quality[a][(lane, i)]["pass"] for a in who):
                answers = ", ".join(sorted({" ".join(quality[a][(lane, i)].get("text", "").split())[:20].strip(".")
                                            or "(empty)" for a in who}))
                w(f"- **Every model got [{i}](#{lane}-{i}) wrong:** \"{cases[(lane, i)]['prompt']}\" "
                  f"Answers given: {cell(answers)}.")
    think = [a for a in models if any(l == "reasoning_think" for (l, _) in quality[a])]
    if think:
        parts = []
        for a in think:
            rs = [r for (l, _), r in quality[a].items() if l == "reasoning_think"]
            out_of_budget = sum(1 for r in rs if not r.get("text", "").strip() and r.get("tokens", 0) >= THINK_BUDGET - 64)
            parts.append(f"`{a}` {sum(r['pass'] for r in rs)}/{len(rs)} correct, {out_of_budget} ran out of budget")
        w(f"- **Thinking mode rarely finishes in {THINK_BUDGET} tokens:** " + "; ".join(parts)
          + ". With thinking off, the same models score 8–9/10.")
    w("- **The chat, code and reasoning questions are too easy to rank models.** Almost every model "
      "scores 9–10/10 on them. They show that each model serves correct output; only vision and "
      "speed separate the models.\n")

    # --- memory -------------------------------------------------------------
    w("## Memory and startup\n")
    w("Before launch, `serve-vllm.sh` predicts how many tokens of context (the KV cache) fit in the "
      "budget; vLLM then logs the real figure.\n")
    w("| Model | Predicted KV tokens | vLLM logged | Error | Concurrency at max context | Engine start |")
    w("|---|---|---|---|---|---|")
    for a in models:
        g = logs[a]
        if not g or not g["logged"]:
            w(f"| `{a}` | — | — | — | — | — |"); continue
        err = f"{(g['pred'] - g['logged']) / g['logged'] * 100:+.1f}%" if g["pred"] else "—"
        w(f"| `{a}` | {g['pred']:,} | {g['logged']:,} | {err} | {f"{float(g['conc'][1]):.1f}× at {g['conc'][0]}" if g['conc'] else '—'} | {g['init'] or '—'} s |")
    w("\nAn error of a few percent is expected: the prediction allows a fixed 1.5 GB for activations. "
      "That is too little for the 32B models and for `vision`'s image encoder. Qwen3.5 models start "
      "slowly the first time they are served (kernel compilation), and in about 15 s after that.\n")

    # --- grids --------------------------------------------------------------
    w("## Results grid\n")
    w("✅ correct · ❌ wrong · — not run for this model\n")
    for lane in LANES:
        ids = sorted({i for (l, i) in cases if l == lane})
        cols = [a for a in models if any((lane, i) in quality[a] for i in ids)]
        if not cols:
            continue
        w(f"### {LANE_TITLES[lane]}\n")
        w("| Case | " + " | ".join(f"`{a}`" for a in cols) + " |")
        w("|---" * (len(cols) + 1) + "|")
        for i in ids:
            marks = ["—" if (lane, i) not in quality[a] else ("✅" if quality[a][(lane, i)]["pass"] else "❌")
                     for a in cols]
            w(f"| [{i}](#{lane.replace('_', '-')}-{i}) | " + " | ".join(marks) + " |")
        totals = [f"**{sum(quality[a][(lane, i)]['pass'] for i in ids if (lane, i) in quality[a])}"
                  f"/{sum(1 for i in ids if (lane, i) in quality[a])}**" for a in cols]
        w("| **Total** | " + " | ".join(totals) + " |\n")

    # --- every case ---------------------------------------------------------
    w("## Every question and answer\n")
    w("Answers are shortened to about 120 characters; the stored answers were cut at 400. "
      "Line breaks are shown as spaces.\n")
    for lane in LANES:
        ids = sorted({i for (l, i) in cases if l == lane})
        if not any(ran(lane, i) for i in ids):
            continue
        w(f"### {LANE_TITLES[lane]}\n")
        for i in ids:
            who = ran(lane, i)
            if not who:
                continue
            c = cases[(lane, i)]
            npass = sum(quality[a][(lane, i)]["pass"] for a in who)
            w(f'<a id="{lane.replace("_", "-")}-{i}"></a>\n')
            w(f"#### {i}: {npass}/{len(who)} correct\n")
            if "image" in c:
                w(f'<img src="bench/images/{c["image"]}" width="140" alt="{c["image"]}">\n')
            w(f"> {c['prompt']}\n")
            w(f"Expected: answer matches `{c['check']}` (case-insensitive)\n")
            w("| Model | Result | Answer | Time to first token |\n|---|---|---|---|")
            for a in who:
                r = quality[a][(lane, i)]
                w(f"| `{a}` | {'✅' if r['pass'] else '❌'} | {snippet(r)} | "
                  f"{r['ttft_s'] * 1000:.0f} ms |" if "ttft_s" in r else
                  f"| `{a}` | ❌ | {snippet(r)} | — |")
            w("")

    # --- notes --------------------------------------------------------------
    w("## Notes\n")
    w("- Scores come from a regular expression, so a correct answer in an unexpected form can be "
      "marked wrong, and vice versa. The answers above let you judge each case yourself.")
    w("- The vision images are synthetic: shapes, colours, text and a bar chart drawn for this test "
      "(`bench/images/`). They test basic perception, not real-world photos.")
    w(f"- Other users on the GPU during each run: " + ", ".join(f"`{a}` {other_users(summaries[a])}" for a in models) + ".")
    w("- Raw data: `bench/results/<model>-<date>.jsonl`, one line per request.")

    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {OUT}: {len(L)} lines, {len(models)} models")


if __name__ == "__main__":
    main()
